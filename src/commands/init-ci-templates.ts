/**
 * GitHub Actions workflow templates for shiori CI integration.
 *
 * Each template is a pure function returning YAML string content.
 * Template selection is driven by CiTemplateKind.
 */

/** Available CI template kinds */
export type CiTemplateKind = 'basic' | 'sarif' | 'delta-pr-comment';

/** All valid CI template kinds (single source of truth) */
export const CI_TEMPLATE_KINDS: readonly CiTemplateKind[] = [
  'basic',
  'sarif',
  'delta-pr-comment',
];

/** Human-readable label for each CI template kind */
export const CI_TEMPLATE_LABELS: Record<CiTemplateKind, string> = {
  basic: 'Basic check (scan + verify on push/PR)',
  sarif: 'SARIF upload (scan + verify + GitHub Code Scanning)',
  'delta-pr-comment': 'Delta PR comment (baseline + PR diff + comment)',
};

/** Output file path for each template kind */
export const CI_TEMPLATE_PATHS: Record<CiTemplateKind, string> = {
  basic: '.github/workflows/shiori.yml',
  sarif: '.github/workflows/shiori.yml',
  'delta-pr-comment': '.github/workflows/shiori.yml',
};

/**
 * Generate a CI workflow YAML for the given template kind.
 * Pure function — no I/O.
 */
export function generateCiWorkflow(kind: CiTemplateKind): string {
  switch (kind) {
    case 'basic':
      return BASIC_TEMPLATE;
    case 'sarif':
      return SARIF_TEMPLATE;
    case 'delta-pr-comment':
      return DELTA_PR_COMMENT_TEMPLATE;
  }
}

