import { access, readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import type { ScanResult } from './types.ts';
import type { ResolvedConfig } from './config.ts';
import { DEFAULT_SCAN_RESULT_PATH } from './config.ts';
import { isNodeError, ScanResultNotFoundError } from './errors.ts';

export interface LoadScanResultOptions {
  /** Value of --scan argument (undefined if not provided, "-" for stdin) */
  explicitPath: string | undefined;
  config: ResolvedConfig;
  cwd: string;
}

/**
 * Resolve the scan result file path from options (without loading).
 *
 * Returns the absolute path if a file-based source is found, or null
 * if the source is stdin.
 */
export async function resolveScanResultPath(
  options: Pick<LoadScanResultOptions, 'explicitPath' | 'config' | 'cwd'>,
): Promise<string | null> {
  const { explicitPath, config, cwd } = options;

  if (explicitPath === '-') return null;
  if (explicitPath) return resolve(cwd, explicitPath);
  if (!process.stdin.isTTY) return null;

  const candidates = buildCandidates(config, cwd);
  for (const candidate of candidates) {
    try {
      await access(candidate.path);
      return candidate.path;
    } catch (err) {
      if (isNodeError(err) && err.code === 'ENOENT') continue;
      throw err;
    }
  }
  return null;
}

/**
 * Build file-based resolution candidates.
 */
function buildCandidates(
  config: ResolvedConfig,
  cwd: string,
): { label: string; path: string }[] {
  const candidates: { label: string; path: string }[] = [];
  const configPath = config.paths.scanResult;
  const configFullPath = resolve(cwd, configPath);

  if (configPath !== DEFAULT_SCAN_RESULT_PATH) {
    candidates.push({ label: `config: ${configPath}`, path: configFullPath });
    candidates.push({
      label: DEFAULT_SCAN_RESULT_PATH,
      path: resolve(cwd, DEFAULT_SCAN_RESULT_PATH),
    });
  } else {
    candidates.push({
      label: DEFAULT_SCAN_RESULT_PATH,
      path: configFullPath,
    });
  }

  return candidates;
}

/**
 * Load scan result from the best available source.
 *
 * Resolution order:
 * 1. --scan <path> explicit argument
 * 2. --scan - → stdin
 * 3. --scan not set, stdin is piped → stdin
 * 4. config.paths.scanResult
 * 5. .config/shiori/scan-result.json (hardcoded default)
 * 6. Error with tried sources listed
 */
export async function loadScanResult(
  options: LoadScanResultOptions,
): Promise<ScanResult> {
  const { explicitPath, config, cwd } = options;

  // 1. Explicit path (resolve relative paths against cwd)
  if (explicitPath && explicitPath !== '-') {
    return loadScanResultFromFile(resolve(cwd, explicitPath));
  }

  // 2. Explicit stdin request
  if (explicitPath === '-') {
    return readFromStdin();
  }

  // 3. Piped stdin (non-TTY)
  if (!process.stdin.isTTY) {
    return readFromStdin();
  }

  // 4-5. File-based resolution
  const candidates = buildCandidates(config, cwd);

  for (const candidate of candidates) {
    try {
      await access(candidate.path);
      return await loadScanResultFromFile(candidate.path);
    } catch (err) {
      if (isNodeError(err) && err.code === 'ENOENT') {
        // not found, try next
        continue;
      }
      throw err;
    }
  }

  const tried = [
    '  stdin (not piped)',
    ...candidates.map((c) => `  ${c.label} (not found)`),
  ].join('\n');
  throw new Error(`No scan result found. Tried:\n${tried}`);
}

/**
 * Minimal shape validation for parsed scan result JSON.
 * Ensures the top-level structure has an `annotations` array.
 */
function assertScanResultShape(
  data: unknown,
  source: string,
): asserts data is ScanResult {
  if (typeof data !== 'object' || data === null || Array.isArray(data)) {
    throw new Error(
      `Invalid scan result from ${source}: expected an object with "annotations" array.`,
    );
  }
  const obj = data as Record<string, unknown>;
  if (!Array.isArray(obj['annotations'])) {
    throw new Error(
      `Invalid scan result from ${source}: missing or invalid "annotations" array.\nEnsure the file was generated by 'shiori scan'.`,
    );
  }
}

/**
 * Load and validate a scan result from a specific file path.
 * Exported for direct use by commands that resolve paths themselves (e.g. delta).
 */
export async function loadScanResultFromFile(
  filePath: string,
): Promise<ScanResult> {
  let content: string;
  try {
    content = await readFile(filePath, 'utf-8');
  } catch (err) {
    if (isNodeError(err) && err.code === 'ENOENT') {
      throw new ScanResultNotFoundError(filePath);
    }
    if (isNodeError(err) && err.code === 'EACCES') {
      throw new Error(
        `Permission denied reading scan result file: ${filePath}`,
      );
    }
    throw err;
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(content);
  } catch {
    throw new Error(
      `Failed to parse scan result as JSON: ${filePath}\nEnsure the file contains valid JSON from 'shiori scan'.`,
    );
  }

  assertScanResultShape(parsed, filePath);
  return parsed;
}

async function readFromStdin(): Promise<ScanResult> {
  const chunks: Buffer[] = [];
  for await (const chunk of process.stdin) {
    // shiori: DEV-015 reason="process.stdin async iterator yields Buffer|string depending on encoding; default binary mode yields Buffer but type is not narrowed"
    chunks.push(chunk as Buffer);
  }
  const content = Buffer.concat(chunks).toString('utf-8');

  if (content.trim() === '') {
    throw new Error(
      "No input received on stdin.\nRun 'shiori scan' first and pipe the output, or use '--scan <path>' to specify a file.",
    );
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(content);
  } catch {
    throw new Error(
      "Failed to parse stdin input as JSON.\nEnsure the piped input is valid JSON from 'shiori scan'.",
    );
  }

  assertScanResultShape(parsed, 'stdin');
  return parsed;
}
